import assert from 'node:assert/strict';
import fs from 'node:fs';
import { planOffers } from './trading-offer-plan.mjs';
import { nativeOffer as native } from './trading-native-offer.mjs';

const stages = ['Novice', 'Apprentice', 'Journeyman', 'Expert', 'Master'];
const xpByLevel = [1, 5, 10, 15, 20];
const professions = ['toolsmith', 'armorer', 'weaponsmith', 'fletcher', 'leatherworker', 'farmer',
  'butcher', 'fisherman', 'shepherd', 'librarian', 'cleric', 'mason', 'cartographer'];
let seed = 0x6d7b8c4f;
const random = () => {
  seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
  return seed / 2 ** 32;
};
function nativePlan(catalog, { offers, saleGroup }) {
  const rolled = {};
  const sales = [];
  const purchases = [];
  const map_slots = [];
  for (const [index, { stage, offer }] of offers.entries()) {
    const slot = index + 1;
    const level = stages.indexOf(stage) + 1;
    assert(level >= 1);
    const direction = offer?.direction ?? 'sell';
    const entry = { level, kind: 0, xp: xpByLevel[level - 1], direction };
    if (offer) Object.assign(entry, { item: offer.item, native: native(offer) });
    if (catalog.profession === 'minecraft:cartographer' && (!offer || offer.item === 'minecraft:spyglass')) {
      const maps = catalog.stages[level - 1].sales.flatMap(group => group.groups.flatMap(pool => pool.candidates))
        .filter(candidate => candidate.resolveDestination);
      map_slots.push({ slot, choices: maps.map(candidate => ({
        destination: candidate.variant, table: candidate.lootTable, native: native(candidate),
      })) });
    }
    rolled['o' + slot] = entry;
    (direction === 'sell' ? sales : purchases).push(slot);
  }
  assert.equal(sales.length + purchases.length, offers.length);
  return { rolled, order: [...sales, ...purchases], ...(saleGroup ? { sale_group: saleGroup } : {}),
    ...(map_slots.length ? { map_slots } : {}) };
}

function fixturePlans(catalog, villagerType, count) {
  const templates = [];
  const distinct = new Set();
  for (let attempt = 0; templates.length < count && attempt < 10000; attempt++) {
    const plan = planOffers(catalog, { random, villagerType });
    const key = JSON.stringify(plan.offers);
    if (distinct.has(key)) continue;
    distinct.add(key);
    templates.push(nativePlan(catalog, plan));
  }
  assert.equal(templates.length, count, 'Not enough compatible fixture plans for ' + catalog.profession);
  return templates;
}

const output = new URL('../modules/experimental/trades/data/iota_trades/function/catalog/current_templates.mcfunction', import.meta.url);
const lines = ['# Generated by tools/build-trading-runtime-probe.mjs. Opt-in current catalog fixtures.'];
let written = 0;
for (const profession of professions) {
  const file = new URL('../docs/discovery/drafts/trading_' + profession + '_catalog.json', import.meta.url);
  const catalog = JSON.parse(fs.readFileSync(file, 'utf8'));
  const villagerTypes = Object.keys(catalog.sharedRules.treasureSpecialty?.biomes ?? {});
  const variants = villagerTypes.length ? villagerTypes : ['plains'];
  const count = profession === 'toolsmith' ? 16 : villagerTypes.length ? 4 : 8;
  for (const type of variants) {
    const key = profession + '_current' + (villagerTypes.length ? '_' + type : '');
    const templates = fixturePlans(catalog, type, count);
    if (profession === 'mason') assert.equal(new Set(templates.map(template => template.sale_group)).size, 2);
    for (const [index, template] of templates.entries()) {
      lines.push('data modify storage iota_trades:templates ' + key + '.p' + index + ' set value ' + JSON.stringify(template));
      written++;
    }
  }
}
fs.writeFileSync(output, lines.join('\n') + '\n');
console.log('Wrote ' + written + ' probe templates across ' + professions.length + ' professions');
